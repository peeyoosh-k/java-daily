// Store two numbers in variables and print their sum.

public class AddTwoNumbers {
    public static void main(String[] args) {

        int num1 = 30;
        int num2 = 90;
        int sum = num1 + num2;
        System.out.println("Sum of " + num1 + " and " + num2 + " = " + sum);
    }
}

// Output
// Sum of 30 and 90 = 120